#!/usr/bin/env node
// Installs the Overtake native messaging host (the broker) for Google Chrome and
// writes the project's .mcp.json for Claude Code.
//
//   node scripts/install.mjs                      # your Chrome (default profile dir)
//   node scripts/install.mjs --user-data-dir DIR  # a specific Chrome user-data dir (tests)
//   node scripts/install.mjs --home DIR           # alternative OVERTAKE_HOME (tests)
//   node scripts/install.mjs --uninstall

import { mkdirSync, writeFileSync, chmodSync, readFileSync, existsSync, rmSync } from 'node:fs';
import { homedir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { randomBytes } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { build } from 'esbuild';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const opt = (n) => {
  const i = args.indexOf(n);
  return i >= 0 ? args[i + 1] : undefined;
};
const HOST = 'dev.overtake.broker';
const extId = readFileSync(join(root, 'keys', 'extension-id.txt'), 'utf8').trim();
const home = opt('--home') || process.env.OVERTAKE_HOME || join(homedir(), '.overtake');
const userDataDir = opt('--user-data-dir');
const hostDirs = userDataDir
  ? [join(userDataDir, 'NativeMessagingHosts')]
  : [join(homedir(), 'Library', 'Application Support', 'Google', 'Chrome', 'NativeMessagingHosts')];

if (args.includes('--uninstall')) {
  for (const d of hostDirs) rmSync(join(d, `${HOST}.json`), { force: true });
  console.log('Removed native host manifest(s). ~/.overtake was left in place.');
  process.exit(0);
}

// 1. State dir + token (owner-only)
for (const d of [home, join(home, 'run'), join(home, 'logs'), join(home, 'bin')]) {
  mkdirSync(d, { recursive: true, mode: 0o700 });
  chmodSync(d, 0o700);
}
const tokenPath = join(home, 'token');
if (!existsSync(tokenPath)) writeFileSync(tokenPath, randomBytes(32).toString('hex') + '\n', { mode: 0o600 });
chmodSync(tokenPath, 0o600);

// 2. Broker: bundled into one self-contained file under the state dir. Chrome's
//    child processes cannot read TCC-protected folders such as ~/Desktop, so the
//    native host must not depend on the repository location. Chrome also starts
//    native hosts with a minimal environment, so pin the absolute node binary.
// Prefer a stable symlink over Homebrew's versioned Cellar path (survives `brew upgrade`).
const node = ['/opt/homebrew/bin/node', '/usr/local/bin/node'].find((p) => process.execPath.includes('/Cellar/') && existsSync(p)) || process.execPath;
const brokerBundle = join(home, 'bin', 'broker.mjs');
await build({
  entryPoints: [join(root, 'bridge', 'broker.ts')], bundle: true, platform: 'node', format: 'esm', target: 'node22',
  outfile: brokerBundle, logLevel: 'warning', banner: { js: '// Overtake broker (generated by scripts/install.mjs)' },
});
chmodSync(brokerBundle, 0o600);
const launcher = join(home, 'bin', 'overtake-broker');
writeFileSync(
  launcher,
  `#!/bin/sh\n# Generated by Overtake scripts/install.mjs\n${opt('--home') ? `export OVERTAKE_HOME='${home}'\n` : ''}exec '${node}' '${brokerBundle}' "$@" 2>>'${join(home, 'logs', 'broker.stderr.log')}'\n`,
  { mode: 0o700 },
);
chmodSync(launcher, 0o700);

// 3. Native messaging host manifest: only our extension id may launch it.
const manifest = { name: HOST, description: 'Overtake broker (agent bridge)', path: launcher, type: 'stdio', allowed_origins: [`chrome-extension://${extId}/`] };
for (const d of hostDirs) {
  mkdirSync(d, { recursive: true });
  writeFileSync(join(d, `${HOST}.json`), JSON.stringify(manifest, null, 2) + '\n');
}

// 4. Build the extension.
execFileSync(node, [join(root, 'scripts', 'build.mjs')], { stdio: 'inherit' });

// 5. Claude Code project MCP config.
if (!userDataDir) {
  const mcpPath = join(root, '.mcp.json');
  const cfg = existsSync(mcpPath) ? JSON.parse(readFileSync(mcpPath, 'utf8')) : { mcpServers: {} };
  cfg.mcpServers ||= {};
  cfg.mcpServers['overtake'] = { command: node, args: [join(root, 'mcp', 'server.ts')] };
  writeFileSync(mcpPath, JSON.stringify(cfg, null, 2) + '\n');
}

console.log(`
Overtake installed.
  extension id : ${extId}
  extension dir: ${join(root, 'dist', 'extension')}
  native host  : ${hostDirs.map((d) => join(d, HOST + '.json')).join(', ')}
  state dir    : ${home}

Next:
  1. chrome://extensions → Developer mode → "Load unpacked" → select the extension dir above.
  2. In Claude Code (run from ${root}) approve the "overtake" MCP server from .mcp.json,
     or register it globally:  claude mcp add --scope user overtake -- '${node}' '${join(root, 'mcp', 'server.ts')}'
`);
